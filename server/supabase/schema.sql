-- CrossFit e Hyrox. A grade é fixa; treino e check-in são de uma data.
-- Rode este trecho no SQL editor do Supabase.

create table if not exists public.class_students (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  auth_user_id uuid unique references auth.users (id) on delete set null,
  name text not null,
  email text not null,
  crossfit boolean not null default false,
  hyrox boolean not null default false,
  created_at timestamptz not null default now(),
  check (crossfit or hyrox)
);

alter table public.class_students
  add column if not exists crossfit boolean not null default false;
alter table public.class_students
  add column if not exists hyrox boolean not null default false;

alter table public.class_students drop constraint if exists class_students_modality_check;
alter table public.class_students
  add constraint class_students_modality_check
  check (crossfit or hyrox);

create unique index if not exists class_students_email_lower_idx
  on public.class_students (lower(email));

alter table public.class_students
  add column if not exists username text;
alter table public.class_students
  add column if not exists phone text;

create unique index if not exists class_students_username_lower_idx
  on public.class_students (lower(username));

notify pgrst, 'reload schema';
create index if not exists class_students_user_id_idx
  on public.class_students (user_id);

create table if not exists public.class_days (
  user_id uuid not null references auth.users (id) on delete cascade,
  modality text not null check (modality in ('crossfit', 'hyrox')),
  day text not null check (day in ('seg', 'ter', 'qua', 'qui', 'sex', 'sab', 'dom')),
  primary key (user_id, modality, day)
);

create table if not exists public.class_slots (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  modality text not null check (modality in ('crossfit', 'hyrox')),
  day text not null check (day in ('seg', 'ter', 'qua', 'qui', 'sex', 'sab', 'dom')),
  time text not null,
  capacity int not null check (capacity > 0 and capacity <= 500),
  created_at timestamptz not null default now(),
  unique (user_id, modality, day, time)
);

create index if not exists class_slots_user_modality_idx
  on public.class_slots (user_id, modality);

create table if not exists public.class_workouts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  modality text not null check (modality in ('crossfit', 'hyrox')),
  workout_on date not null,
  body text not null default '',
  unique (user_id, modality, workout_on)
);

create table if not exists public.class_checkins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  student_id bigint references public.class_students (id) on delete set null,
  slot_id bigint references public.class_slots (id) on delete set null,
  student_name text not null,
  modality text not null check (modality in ('crossfit', 'hyrox')),
  day text not null check (day in ('seg', 'ter', 'qua', 'qui', 'sex', 'sab', 'dom')),
  time text not null,
  class_on date not null,
  created_at timestamptz not null default now()
);

create unique index if not exists class_checkins_student_slot_date_idx
  on public.class_checkins (student_id, modality, class_on, time)
  where student_id is not null;

create index if not exists class_checkins_user_date_idx
  on public.class_checkins (user_id, class_on);
create index if not exists class_checkins_slot_date_idx
  on public.class_checkins (slot_id, class_on);

