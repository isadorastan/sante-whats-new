create table if not exists public.students (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null,
  phone text not null default '',
  weekly_classes int not null default 1,
  plan_value numeric(10, 2) not null default 0,
  color text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  student_id bigint not null references public.students (id) on delete cascade,
  day text not null check (day in ('seg', 'ter', 'qua', 'qui', 'sex', 'sab', 'dom')),
  time text not null,
  duration_minutes int not null default 45,
  created_at timestamptz not null default now(),
  unique (student_id, day, time)
);

create index if not exists sessions_day_idx on public.sessions (day);
create index if not exists sessions_student_id_idx on public.sessions (student_id);

-- Banco que já existia antes de user_id: a create table acima não altera a tabela.
alter table public.students
  add column if not exists user_id uuid references auth.users (id) on delete cascade;
alter table public.sessions
  add column if not exists user_id uuid references auth.users (id) on delete cascade;

create index if not exists students_user_id_idx on public.students (user_id);
create index if not exists sessions_user_id_idx on public.sessions (user_id);

