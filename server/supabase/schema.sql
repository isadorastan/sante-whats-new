alter table public.students alter column user_id set not null;
alter table public.sessions alter column user_id set not null;

-- A API usa a secret key, que ignora RLS. A policy trava a chave anônima.
alter table public.students enable row level security;
alter table public.sessions enable row level security;

drop policy if exists students_own on public.students;
create policy students_own on public.students
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists sessions_own on public.sessions;
create policy sessions_own on public.sessions
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

