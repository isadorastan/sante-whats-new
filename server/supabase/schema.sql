-- Estatísticas: situação do aluno, tabela vigente e pagamentos do mês.
alter table public.students
  add column if not exists status text not null default 'ativo';
alter table public.students
  add column if not exists started_on date;
alter table public.students
  add column if not exists ended_on date;
alter table public.students
  add column if not exists billing_day integer;
alter table public.students
  add column if not exists custom_price boolean not null default false;

alter table public.students drop constraint if exists students_status_check;
alter table public.students
  add constraint students_status_check
  check (status in ('ativo', 'pausado', 'encerrado'));

alter table public.students drop constraint if exists students_billing_day_check;
alter table public.students
  add constraint students_billing_day_check
  check (billing_day is null or (billing_day >= 1 and billing_day <= 28));

create table if not exists public.plan_prices (
  user_id uuid not null references auth.users (id) on delete cascade,
  weekly_classes int not null check (weekly_classes between 1 and 7),
  amount numeric(10, 2) not null check (amount >= 0),
  primary key (user_id, weekly_classes)
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  student_id bigint not null references public.students (id) on delete cascade,
  competence date not null,
  amount numeric(10, 2) not null check (amount >= 0),
  due_on date,
  paid_on date,
  unique (student_id, competence)
);

create index if not exists payments_user_competence_idx
  on public.payments (user_id, competence);

alter table public.plan_prices enable row level security;
alter table public.payments enable row level security;

drop policy if exists plan_prices_own on public.plan_prices;
create policy plan_prices_own on public.plan_prices
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists payments_own on public.payments;
create policy payments_own on public.payments
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
